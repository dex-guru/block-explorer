import { GetServerSidePropsContext, NextPage } from 'next'
import Head from 'next/head'
import Link from 'next/link'
import clsx from 'clsx'
import styles from '../Pages.module.scss'
import { BlockModel } from '@/__generated__/resolvers-types'
import {
  Address,
  DateTime,
  Page,
  Properties,
  TimeAgo,
  Value,
} from '@/components'
import { AddressValues } from '@/components/Address/helpers'
import DetailsView from '@/components/DetailsView/DetailsView'
import ArrowLeft from '@/images/icons/arrow-left.svg'
import ArrowRight from '@/images/icons/arrow-right.svg'
import StopwatchIcon from '@/images/icons/stop-watch.svg'
import { addApolloState, initializeApollo } from '@/lib/apollo/client'
import { GET_BLOCKS_BY_NUMBER } from '@/lib/apollo/queries'
import { financialFormat } from '@/lib/utils'

interface IBlockProps {
  data: BlockModel | null
}

const Block: NextPage<IBlockProps> = ({ data }) => {
  if (!data) {
    return <></>
  }

  return (
    <>
      <Head>
        <title>Transaction detail page</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <Page withSearch>
        <DetailsView
          title={
            <>
              Block <span className={styles.muted}>#{data.number}</span>
            </>
          }
        >
          <Properties
            data={[
              {
                title: 'Block Height:',
                value: (
                  <>
                    {data.number}{' '}
                    <Link
                      href={AddressValues['block'].url(`${data.number - 1}`)}
                      className={clsx(styles.pageTo, {
                        [styles.disabled]: data.number < 2,
                      })}
                    >
                      <ArrowLeft className={styles.icon} />
                    </Link>
                    <Link
                      href={AddressValues['block'].url(`${data.number + 1}`)}
                      className={styles.pageTo}
                    >
                      <ArrowRight className={styles.icon} />
                    </Link>
                  </>
                ),
                tooltip: '?',
              },
              { title: 'Status:', value: '', tooltip: '?' },
              {
                title: 'Timestamp:',
                tooltip: '?',
                value: (
                  <Value
                    icon={<StopwatchIcon />}
                    value={
                      <>
                        <TimeAgo timestamp={data.timestamp} />{' '}
                        <span className={styles.muted}>
                          (
                          <DateTime
                            timestamp={data.timestamp}
                            className={styles.muted}
                          />
                          )
                        </span>
                      </>
                    }
                  />
                ),
              },
              { title: 'Proposed On:', tooltip: '?', value: '' },
              {
                title: 'Transactions:',
                tooltip: '?',
                value: (
                  <Link href={`/txs?block=${data.number}?`}>
                    {financialFormat(data.transactionCount)}
                  </Link>
                ),
              },
              {
                title: 'Withdrawals:',
                tooltip: '?',
                value: '',
              },
              {
                title: 'Fee Recipient:',
                tooltip: '?',
                value: (
                  <Address
                    type="account"
                    address={data.miner}
                    isShorten={false}
                  />
                ),
              },
              {
                title: 'Block Reward:',
                tooltip: '?',
                value: '',
              },
              {
                title: 'Total Difficulty:',
                tooltip: '?',
                value: '',
              },
              {
                title: 'Size:',
                tooltip: '?',
                value: financialFormat(data.size),
              },
              {
                title: 'Gas Used:',
                tooltip: data.gasUsed,
                value: financialFormat(data.size),
              },
              {
                title: 'Gas Limit:',
                tooltip: '?',
                value: financialFormat(data.gasLimit),
              },
              {
                title: 'Base Fee Per Gas:',
                tooltip: '?',
                value: financialFormat(data.baseFeePerGas || 0),
              },
              {
                title: 'Burnt Fees:',
                tooltip: '?',
                value: '',
              },
              {
                title: 'Extra Data:',
                tooltip: '?',
                value: data.extraData,
              },
            ]}
          />
        </DetailsView>
      </Page>
    </>
  )
}

export default Block

export const getServerSideProps = async (ctx: GetServerSidePropsContext) => {
  const apolloClient = initializeApollo({ ctx })

  const { slug } = ctx.query
  const number = (slug as string[])[0]

  const { data } = await apolloClient.query<{
    blocks: BlockModel[]
  }>({
    query: GET_BLOCKS_BY_NUMBER,
    variables: { number: Number(number) },
  })

  let blocks: BlockModel | null = null

  if (data.blocks.length) {
    blocks = data.blocks[0]
  }

  return addApolloState(apolloClient, {
    props: { data: blocks },
  })
}

export const config = {
  runtime: 'experimental-edge',
}
