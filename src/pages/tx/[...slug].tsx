import { GetServerSidePropsContext, NextPage } from 'next'
import Head from 'next/head'
import { TransactionModel } from '@/__generated__/resolvers-types'
import { Address, Page, Properties, TimeAgo, Value } from '@/components'
import DetailsView from '@/components/DetailsView/DetailsView'
import StopwatchIcon from '@/images/icons/stop-watch.svg'
import { addApolloState, initializeApollo } from '@/lib/apollo/client'
import { GET_TRANSACTIONS_BY_HASH } from '@/lib/apollo/queries'

interface ITxProps {
  data: TransactionModel | null
}

const Tx: NextPage<ITxProps> = ({ data }) => {
  if (!data) {
    return <></>
  }

  const transactionsTime = new Date(data.blockTimestamp * 1000).toUTCString()
  const blockTime = new Date(data.blockTimestamp * 1000).toUTCString()

  return (
    <>
      <Head>
        <title>Transaction detail page</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <Page withSearch>
        <DetailsView title="Transaction Details">
          <Properties
            data={[
              {
                title: 'Transaction Hash:',
                tooltip: '?',
                value: data.hash,
              },
              {
                title: 'Status:',
                tooltip: '?',
                value: (
                  <Value
                    icon={<StopwatchIcon />}
                    value={
                      <>
                        <TimeAgo timestamp={data.blockTimestamp} />
                        {`(${transactionsTime})`}
                      </>
                    }
                  />
                ),
              },
              {
                title: 'Block / Position:',
                tooltip: '?',
                value: <Address type="block" address={`${data.blockNumber}`} />,
              },
              {
                title: 'Timestamp:',
                tooltip: '?',
                value: (
                  <Value
                    icon={<StopwatchIcon />}
                    value={
                      <>
                        <TimeAgo timestamp={data.blockTimestamp} />{' '}
                        <span className="muted">({blockTime})</span>
                      </>
                    }
                  />
                ),
              },
              {
                title: 'From / Nonce:',
                tooltip: '?',
                value: (
                  <>
                    <Address
                      address={data.fromAddress}
                      type="account"
                      isShorten={false}
                    />{' '}
                    <span className="muted">| {data.nonce}</span>
                  </>
                ),
              },
              {
                title: 'Interacted With (To):',
                tooltip: '?',
                value: data.toAddress ? (
                  <Address
                    address={data.toAddress}
                    type="account"
                    isShorten={false}
                  />
                ) : null,
              },
              {
                title: 'Transaction Action:',
                tooltip: '?',
                value: '',
              },
              {
                title: 'Transaction Hash:',
                tooltip: '?',
                value: '',
              },
              {
                title: 'Status:',
                tooltip: '?',
                value: '',
              },
            ]}
          />
        </DetailsView>
      </Page>
    </>
  )
}

export default Tx

export const getServerSideProps = async (ctx: GetServerSidePropsContext) => {
  const apolloClient = initializeApollo({ ctx })

  const { slug } = ctx.query
  const hash = (slug as string[])[0]

  const { data } = await apolloClient.query<{
    transactions: TransactionModel[]
  }>({
    query: GET_TRANSACTIONS_BY_HASH,
    variables: { hash },
  })

  let transactions: TransactionModel | null = null

  if (data.transactions.length) {
    transactions = data.transactions[0]
  }

  return addApolloState(apolloClient, {
    props: { data: transactions },
  })
}

export const config = {
  runtime: 'experimental-edge',
}
