import { Suspense, lazy } from 'react'
import { GetServerSidePropsContext, NextPage } from 'next'
import Head from 'next/head'
import { useRouter } from 'next/router'
import { LogModel, TransactionModel } from '@/__generated__/resolvers-types'
import { Empty, Page, TabPanel } from '@/components'
import DetailsView from '@/components/DetailsView/DetailsView'
import IconEmpty from '@/images/icons/no-flash.svg'
import { addApolloState, initializeApollo } from '@/lib/apollo/client'
import { GET_TRANSACTION_BY_HASH } from '@/lib/apollo/queries'

const TxOverview = lazy(() => import('./tabs/TxOverview'))
const TxLogs = lazy(() => import('./tabs/TxLogs'))
const TxTrace = lazy(() => import('./tabs/TxTrace'))

interface ITxProps {
  data: TransactionModel | null
  logs: LogModel[] | null
}

const Tx: NextPage<ITxProps> = ({ data, logs }) => {
  const router = useRouter()
  const { tab } = router.query
  const pathname = router.asPath.split('?')[0]

  return (
    <>
      <Head>
        <title>Transaction detail page</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <Page withSearch>
        <DetailsView title="Transaction Details">
          {!data?.hash && (
            <Empty icon={<IconEmpty />} title="No TX  was found" />
          )}

          {!!data?.hash && (
            <TabPanel
              tabs={[
                {
                  title: 'Overview',
                  value: '',
                  to: pathname,
                  content: (
                    <Suspense>
                      <TxOverview data={data} />
                    </Suspense>
                  ),
                },
                {
                  title: `Logs (${logs?.length || 0})`,
                  value: 'logs',
                  to: `${pathname}?tab=logs`,
                  content: (
                    <Suspense>
                      <TxLogs data={data} logs={logs} />
                    </Suspense>
                  ),
                },
                {
                  title: 'Trace',
                  value: 'trace',
                  to: `${pathname}?tab=trace`,
                  content: (
                    <Suspense>
                      <TxTrace data={data} />
                    </Suspense>
                  ),
                },
              ]}
              value={tab || ''}
            />
          )}
        </DetailsView>
      </Page>
    </>
  )
}

export default Tx

export const getServerSideProps = async (ctx: GetServerSidePropsContext) => {
  const apolloClient = initializeApollo({ ctx })

  const { slug } = ctx.query
  const hash = (slug as string[])[0]

  const { data } = await apolloClient.query<{
    transactions: TransactionModel[]
    logs: LogModel[]
  }>({
    query: GET_TRANSACTION_BY_HASH,
    variables: { hash },
  })

  return addApolloState(apolloClient, {
    props: {
      data: data.transactions[0] || null,
      logs: data.logs || null,
    },
  })
}

export const config = {
  runtime: 'experimental-edge',
}
