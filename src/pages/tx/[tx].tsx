import { Suspense, lazy } from 'react'
import { GetServerSidePropsContext, NextPage } from 'next'
import Head from 'next/head'
import { useRouter } from 'next/router'
import { isHexString } from '@ethersproject/bytes'
import {
  ChainConfigModel,
  ChainStatsModel,
  LogModel,
  TransactionModel,
} from '@/__generated__/resolvers-types'
import { Card, Empty, Page, TabPanel } from '@/components'
import DetailsView from '@/components/DetailsView/DetailsView'
import Loading from '@/components/Loading'
import IconEmpty from '@/images/icons/no-flash.svg'
import { addApolloState, initializeApollo } from '@/lib/apollo/client'
import { GET_TRANSACTIONS_BY_HASH } from '@/lib/apollo/queries'

const TxOverview = lazy(() => import('../../components/TabContent/TxOverview'))
const TxLogs = lazy(() => import('../../components/TabContent/TxLogs'))
const TxTrace = lazy(() => import('../../components/TabContent/TxTrace'))

interface ITxProps {
  data: TransactionModel | null
  logs: LogModel[] | null
  chainStats: ChainStatsModel
  chainConfig: ChainConfigModel
}

const Tx: NextPage<ITxProps> = ({ data, logs, chainStats, chainConfig }) => {
  const router = useRouter()
  const { tab } = router.query
  const pathname = router.asPath.split('?')[0]

  const preloader = (
    <Card>
      <Loading />
    </Card>
  )

  return (
    <>
      <Head>
        <title>Transaction detail page</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <Page withSearch>
        {' '}
        <DetailsView title="Transaction " address={data?.hash || undefined}>
          {!data?.hash && (
            <Empty icon={<IconEmpty />} title="No TX was found" />
          )}

          {!!data?.hash && (
            <TabPanel
              tabs={[
                {
                  title: 'Overview',
                  value: '',
                  to: pathname,
                  content: (
                    <Suspense fallback={preloader}>
                      <TxOverview
                        data={data}
                        chainStats={chainStats}
                        chainConfig={chainConfig}
                      />
                    </Suspense>
                  ),
                },
                {
                  title: `Logs (${logs?.length || 0})`,
                  value: 'logs',
                  to: `${pathname}?tab=logs`,
                  content: (
                    <Suspense fallback={preloader}>
                      <TxLogs data={data} />
                    </Suspense>
                  ),
                },
                {
                  title: 'Trace',
                  value: 'trace',
                  to: `${pathname}?tab=trace`,
                  content: (
                    <Suspense fallback={preloader}>
                      <TxTrace data={data} />
                    </Suspense>
                  ),
                },
              ]}
              value={tab || ''}
            />
          )}
        </DetailsView>
      </Page>
    </>
  )
}

export default Tx

export const getServerSideProps = async (ctx: GetServerSidePropsContext) => {
  const { tx } = ctx.query

  if (!isHexString(tx)) {
    return { notFound: true }
  }

  const apolloClient = initializeApollo({ ctx })

  const { data } = await apolloClient.query<{
    transactions: TransactionModel[]
    logs: LogModel[]
    chainStats: ChainStatsModel
    chainConfig: ChainConfigModel
  }>({
    query: GET_TRANSACTIONS_BY_HASH,
    variables: { hash: tx },
  })

  const { transactions, logs, chainConfig, chainStats } = data

  if (!transactions?.length) {
    return { notFound: true }
  }

  return addApolloState(apolloClient, {
    props: {
      data: transactions[0],
      logs: logs || null,
      chainConfig: chainConfig || null,
      chainStats: chainStats || null,
    },
  })
}

export const config = {
  runtime: 'experimental-edge',
}
